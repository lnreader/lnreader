const {
  AndroidConfig,
  withAndroidColors,
  withAndroidColorsNight,
  withAndroidStyles,
  withAppBuildGradle,
  withDangerousMod,
  withMainActivity,
} = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const BUILD_TYPES_MARKER = '// @generated by with-android-customizations';

const BUILD_TYPES_APPLY = `${BUILD_TYPES_MARKER}
apply from: new File(
    rootDir,
    "../plugins/android/android-build-types.gradle",
)
`;

const ANDROID_ASSET_VARIANTS = [
  { source: 'release', target: 'main' },
  { source: 'preview', target: 'preRelease' },
  { source: 'debug', target: 'debug' },
];

const LAUNCHER_RESOURCE_NAMES = [
  'ic_launcher',
  'ic_launcher_background',
  'ic_launcher_foreground',
  'ic_launcher_monochrome',
  'ic_launcher_round',
];

const DRAWABLE_RESOURCE_NAMES = [
  'notification_icon',
  'splash_icon',
  'splashscreen_logo',
];

/**
 * `AppTheme` inherits `android:windowBackground` from
 * `Theme.AppCompat.DayNight.NoActionBar`, which resolves to a near-white colour
 * whenever the system is in light mode. The window is visible for the frames
 * between the splash screen going away and React drawing its first frame, so
 * the app opens with a white flash for anyone using a dark theme on a light
 * system. These are the backgrounds of the default light and dark themes.
 */
const WINDOW_BACKGROUND_RESOURCE = 'lnreaderWindowBackground';
const WINDOW_BACKGROUND_LIGHT = '#FEFBFF';
const WINDOW_BACKGROUND_DARK = '#1B1B1F';

const withWindowBackgroundColors = config => {
  config = withAndroidColors(config, config => {
    config.modResults = AndroidConfig.Colors.assignColorValue(
      config.modResults,
      { name: WINDOW_BACKGROUND_RESOURCE, value: WINDOW_BACKGROUND_LIGHT },
    );

    return config;
  });

  return withAndroidColorsNight(config, config => {
    config.modResults = AndroidConfig.Colors.assignColorValue(
      config.modResults,
      { name: WINDOW_BACKGROUND_RESOURCE, value: WINDOW_BACKGROUND_DARK },
    );

    return config;
  });
};

const withWindowBackgroundStyle = config =>
  withAndroidStyles(config, config => {
    config.modResults = AndroidConfig.Styles.assignStylesValue(
      config.modResults,
      {
        add: true,
        parent: AndroidConfig.Styles.getAppThemeGroup(),
        name: 'android:windowBackground',
        value: `@color/${WINDOW_BACKGROUND_RESOURCE}`,
      },
    );

    return config;
  });

/**
 * Bar icon styles that match the backgrounds above: dark icons over the light
 * window, light icons over the dark one. Without this the bars keep one fixed
 * style from launch until JS applies the app theme, which leaves them
 * low-contrast over whichever background does not match.
 */
const LIGHT_SYSTEM_BARS_RESOURCE = 'lnreaderLightSystemBars';
const SYSTEM_BAR_ATTRIBUTES = [
  'android:windowLightStatusBar',
  'android:windowLightNavigationBar',
];

/**
 * The splash background is dark for release and debug builds, so its bar
 * icons default to light. The preview variant, whose splash is light,
 * overrides this resource in its own `values`.
 */
const SPLASH_LIGHT_SYSTEM_BARS_RESOURCE = 'lnreaderSplashLightSystemBars';

const boolResourceFile = (
  value,
  splashValue,
) => `<?xml version="1.0" encoding="utf-8"?>
<resources>
  <bool name="${LIGHT_SYSTEM_BARS_RESOURCE}">${value}</bool>${
  splashValue === undefined
    ? ''
    : `
  <bool name="${SPLASH_LIGHT_SYSTEM_BARS_RESOURCE}">${splashValue}</bool>`
}
</resources>
`;

const withLightSystemBarsResources = config =>
  withDangerousMod(config, [
    'android',
    config => {
      const resDir = path.join(
        config.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
      );

      for (const [dir, value, splashValue] of [
        ['values', true, false],
        ['values-night', false],
      ]) {
        fs.mkdirSync(path.join(resDir, dir), { recursive: true });
        fs.writeFileSync(
          path.join(resDir, dir, 'lnreader_system_bars.xml'),
          boolResourceFile(value, splashValue),
        );
      }

      return config;
    },
  ]);

const SPLASH_THEME_GROUP = {
  name: 'Theme.App.SplashScreen',
  parent: 'Theme.SplashScreen',
};

const withSystemBarStyles = config =>
  withAndroidStyles(config, config => {
    for (const name of SYSTEM_BAR_ATTRIBUTES) {
      config.modResults = AndroidConfig.Styles.assignStylesValue(
        config.modResults,
        {
          add: true,
          parent: AndroidConfig.Styles.getAppThemeGroup(),
          name,
          value: `@bool/${LIGHT_SYSTEM_BARS_RESOURCE}`,
        },
      );
      config.modResults = AndroidConfig.Styles.assignStylesValue(
        config.modResults,
        {
          add: true,
          parent: SPLASH_THEME_GROUP,
          name,
          value: `@bool/${SPLASH_LIGHT_SYSTEM_BARS_RESOURCE}`,
        },
      );
    }

    return config;
  });

const withBuildGradleCustomizations = config =>
  withAppBuildGradle(config, config => {
    const { contents } = config.modResults;

    if (!contents.includes(BUILD_TYPES_MARKER)) {
      config.modResults.contents = `${contents.trimEnd()}

${BUILD_TYPES_APPLY}`;
    }

    return config;
  });

const removeGeneratedIconResources = resDir => {
  if (!fs.existsSync(resDir)) {
    return;
  }

  for (const resourceDirName of fs.readdirSync(resDir)) {
    const resourceDir = path.join(resDir, resourceDirName);

    if (!fs.statSync(resourceDir).isDirectory()) {
      continue;
    }

    if (resourceDirName.startsWith('mipmap-')) {
      for (const resourceName of LAUNCHER_RESOURCE_NAMES) {
        for (const extension of ['png', 'webp', 'xml']) {
          fs.rmSync(path.join(resourceDir, `${resourceName}.${extension}`), {
            force: true,
          });
        }
      }
    }

    if (resourceDirName.startsWith('drawable-')) {
      for (const resourceName of DRAWABLE_RESOURCE_NAMES) {
        for (const extension of ['png', 'webp', 'xml']) {
          fs.rmSync(path.join(resourceDir, `${resourceName}.${extension}`), {
            force: true,
          });
        }
      }
    }
  }
};

/**
 * Each variant ships its splash icon as a vector so it stays sharp at any
 * density. It replaces the PNGs expo-splash-screen generates (removed above),
 * and is copied to `drawable-night` so the main source set's night resource
 * cannot outrank a variant's unqualified one.
 */
const installVariantSplashIcon = resDir => {
  const drawableDir = path.join(resDir, 'drawable');
  const splashPath = path.join(drawableDir, 'splashscreen_logo.xml');
  const nightDrawableDir = path.join(resDir, 'drawable-night');

  fs.renameSync(path.join(drawableDir, 'splash_icon.xml'), splashPath);
  fs.mkdirSync(nightDrawableDir, { recursive: true });
  fs.copyFileSync(
    splashPath,
    path.join(nightDrawableDir, 'splashscreen_logo.xml'),
  );
};

const withAndroidVariantAssets = config =>
  withDangerousMod(config, [
    'android',
    config => {
      const { projectRoot, platformProjectRoot } = config.modRequest;

      for (const variant of ANDROID_ASSET_VARIANTS) {
        const sourceResDir = path.join(
          projectRoot,
          'assets',
          'android-icons',
          variant.source,
          'res',
        );
        const targetResDir = path.join(
          platformProjectRoot,
          'app',
          'src',
          variant.target,
          'res',
        );

        removeGeneratedIconResources(targetResDir);
        fs.mkdirSync(targetResDir, { recursive: true });
        fs.cpSync(sourceResDir, targetResDir, { recursive: true });
        installVariantSplashIcon(targetResDir);
      }

      return config;
    },
  ]);

/**
 * Android's "Bold text" accessibility setting (`fontWeightAdjustment`) makes
 * TextView draw glyphs heavier and wider, but React Native measures text
 * without it. Text then overflows its measured box and the last letter or word
 * is clipped everywhere. Drop the adjustment so drawing matches measurement.
 */
const FONT_WEIGHT_MARKER =
  '// @generated by with-android-customizations: font weight';

const FONT_WEIGHT_OVERRIDE = `  ${FONT_WEIGHT_MARKER}
  override fun attachBaseContext(newBase: Context) {
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
      val config = Configuration(newBase.resources.configuration)
      config.fontWeightAdjustment = 0
      super.attachBaseContext(newBase.createConfigurationContext(config))
    } else {
      super.attachBaseContext(newBase)
    }
  }

`;

const withFontWeightAdjustmentDisabled = config =>
  withMainActivity(config, config => {
    let { contents } = config.modResults;

    if (!contents.includes(FONT_WEIGHT_MARKER)) {
      contents = contents
        .replace(
          'import android.os.Bundle',
          'import android.content.Context\nimport android.content.res.Configuration\nimport android.os.Bundle',
        )
        .replace(
          /(class MainActivity : ReactActivity\(\) \{\r?\n)/,
          `$1${FONT_WEIGHT_OVERRIDE}`,
        );
      config.modResults.contents = contents;
    }

    return config;
  });

module.exports = config => {
  config = withBuildGradleCustomizations(config);
  config = withFontWeightAdjustmentDisabled(config);
  config = withWindowBackgroundColors(config);
  config = withWindowBackgroundStyle(config);
  config = withLightSystemBarsResources(config);
  config = withSystemBarStyles(config);
  return withAndroidVariantAssets(config);
};
